'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { EventStore, applyUpdate } = require('./store.cjs');
const { frame } = require('./server.cjs');
const { experiment } = require('./replay.cjs');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gurukul-replay-test-'));
let db;
try {
  const filename = path.join(dir, 'test.sqlite');
  db = new EventStore(filename, 3); db.create('order-41'); db.create('order-99');
  assert.equal(db.resume('order-41').mode, 'snapshot');
  db.append('order-41', 'cooking');
  db.append('order-99', 'ready');
  const ready = db.append('order-41', 'ready');
  assert.deepEqual(db.resume('order-41', 1).rows.map(x => x.seq), [2]);
  assert(db.resume('order-41', 0).rows.every(x => x.stream_id === 'order-41'));
  let ui = { stream_id: 'order-41', seq: 1, state: 'cooking' };
  ui = applyUpdate(ui, ready);
  assert.strictEqual(applyUpdate(ui, ready), ui);
  assert.throws(() => applyUpdate(ui, { ...ready, stream_id: 'order-99' }));
  for (const c of [-1, 0.5, NaN, Infinity, 999, '1']) assert.throws(() => db.resume('order-41', c));
  assert.throws(() => db.append('order-41', 'typo'));
  assert.throws(() => db.append('missing', 'ready'));
  assert.equal(db.head('order-41').head, 2);
  // Force a failure after INSERT; rollback must remove the new history row too.
  db.db.exec("CREATE TRIGGER fail_head BEFORE UPDATE ON streams BEGIN SELECT RAISE(ABORT, 'injected'); END;");
  assert.throws(() => db.append('order-41', 'delivered'), /injected/);
  assert.deepEqual(db.resume('order-41', 0).rows.map(x=>x.seq), [1,2]);
  db.db.exec('DROP TRIGGER fail_head');
  db.append('order-41', 'delivered'); db.append('order-41', 'accepted');
  assert.equal(db.resume('order-41', 0).mode, 'reset');
  assert.deepEqual(db.resume('order-41', 1).rows.map(x => x.seq), [2, 3, 4]);
  assert.equal(db.resume('order-41', 4).rows.length, 0);
  const retainedFive = experiment({ head: 7, retain: 5, cursor: 2 });
  assert.deepEqual(retainedFive.retainedSequences, [3, 4, 5, 6, 7]);
  assert.equal(retainedFive.replayFloor, 2);
  assert.equal(retainedFive.mode, 'replay');
  assert.deepEqual(retainedFive.rows.map(row => row.seq), [3, 4, 5, 6, 7]);
  const expired = experiment({ head: 7, retain: 5, cursor: 1 });
  assert.equal(expired.mode, 'reset');
  assert.deepEqual(expired.rows.map(row => row.seq), [7]);
  assert.deepEqual(experiment({ head: 7, retain: 5, cursor: 7 }).rows, []);
  assert.throws(() => experiment({ head: 7, cursor: 8 }), /Invalid cursor/);
  assert.throws(() => experiment({ retain: 0 }));
  db.close(); db = new EventStore(filename, 3);
  assert.equal(db.head('order-41').head, 4);
  assert.deepEqual(db.resume('order-41', 1).rows.map(x => x.seq), [2, 3, 4]);
  assert.equal(frame('update', ready), 'id: 2\nevent: update\ndata: {"stream_id":"order-41","seq":2,"state":"ready"}\n\n');
  console.log('PASS: scoped replay, duplicate/stale UI updates, invalid cursors, transaction rollback, retention boundary, file reopen, SSE frame.');
  console.log('These tests use real SQLite. HTTP/browser delivery is a separate check.');
} finally { if (db) db.close(); fs.rmSync(dir, { recursive: true }); }
