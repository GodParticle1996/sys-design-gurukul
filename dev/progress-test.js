#!/usr/bin/env node
'use strict';
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), assert = require('node:assert/strict');
const { environment } = require('../tools/mini-dom');
const { perform, fixtures } = require('../tools/replay-exercises');
const root = path.resolve(__dirname, '..'), env = environment(), context = vm.createContext(env.sandbox);
const files = [...fs.readFileSync(path.join(root, 'index.html'), 'utf8').matchAll(/<script\s+src="([^"]+)"/g)].map(m => m[1]);
for (const file of files) vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), context, { filename: file });
const SD = vm.runInContext('SD', context); env.SD = SD;
let checks = 0; const check = (condition, message) => { assert.ok(condition, message); checks++; };
const record = fixtures.find(r => r.type === 'bins');
const original = Object.values(SD.levelSets).flat().find(l => l.id === record.level);
const stage = original.stages[record.stage];
const level = { id: '__progress_regression', title: 'Progress test', icon: '', badge: 'Test', stages: [stage], cards: [], success: [] };
SD.registerLevels('fp-core', [level]);
function start(replay = false) {
  SD.session = { level, stageIdx: 0, firstTry: 0, total: 0, pendingXP: 0, replay };
  SD.ui.runStage(); env.flush();
  return { env, stage, arena: env.document.getElementById('app').querySelector('.arena') };
}
SD.state = SD.defaultState();
let walk = start(); perform(walk, record.solution[0]);
check(SD.state.xp === 0 && SD.session.pendingXP === SD.XP_PER_ITEM, 'partial item does not commit XP');
SD.ui.showHome(); SD.state = SD.loadState();
walk = start(); perform(walk, record.solution[0]);
check(SD.state.xp === 0 && SD.session.pendingXP === SD.XP_PER_ITEM, 'reload/restart cannot accumulate partial item XP');
record.solution.slice(1).forEach(a => perform(walk, a));
const expected = stage.items.length * SD.XP_PER_ITEM + SD.PERFECT_BONUS;
check(SD.state.xp === 0 && SD.state.checkpoint.pendingXP === expected, 'completed challenge buffers and saves XP without level award');
check(SD.state.checkpoint.stageIdx === 1, 'completion checkpoints next challenge boundary');
SD.ui.showHome(); SD.state = SD.loadState(); SD.ui.showHome();
const resume = env.document.getElementById('app').querySelector('.resume-card button'); check(resume, 'pending level can resume after reload');
resume.click(); env.flush();
check(SD.state.xp === expected && SD.state.completed.includes(level.id), 'first full completion commits pending XP once');
check(SD.state.checkpoint === null, 'completed level clears checkpoint');
walk = start(true); record.solution.forEach(a => perform(walk, a));
env.document.getElementById('app').querySelector('.stage-summary button').click(); env.flush();
check(SD.state.xp === expected, 'completed level replay does not earn new XP');
SD.ui.showHome();
const base = SD.state.xp;
SD.awardPopBonus(['same-question', 'same-question']);
check(SD.state.xp === base + SD.POP_XP, 'same question counted once within bonus batch');
SD.state = SD.loadState(); SD.awardPopBonus(['same-question']);
check(SD.state.xp === base + SD.POP_XP, 'reload preserves daily pop-quiz deduplication');
SD.state.dojo = { a: { front: 'A', back: 'AA', box: 0, due: 0 }, b: { front: 'B', back: 'BB', box: 0, due: 0 } };
SD.ui.showDojo();
env.document.getElementById('app').querySelector('.flashcard .btn').click();
const yes = env.document.getElementById('app').querySelector('.flashcard .btn.good'); const before = SD.state.xp;
yes.click(); yes.click(); env.flush();
check(SD.state.xp === before + SD.CARD_XP, 'double review click awards one card only');
check(env.document.getElementById('app').querySelector('.fc-front'), 'double click did not skip the following card');
// Content updates may preserve a title while changing the challenge itself.
// A previously completed stage boundary must not skip the revised challenge.
SD.state = SD.defaultState();
const revisionLevel = { ...level, id: '__progress_content_change', stages: [structuredClone(stage), structuredClone(stage)] };
SD.registerLevels('fp-core', [revisionLevel]);
SD.session = { level: revisionLevel, stageIdx: 0, firstTry: 0, total: 0, pendingXP: 0, replay: false };
SD.ui.runStage(); env.flush();
const revisionWalk = { env, stage: revisionLevel.stages[0], arena: env.document.getElementById('app').querySelector('.arena') };
record.solution.forEach(a => perform(revisionWalk, a));
SD.ui.showHome(); SD.state = SD.loadState(); SD.ui.showHome();
check(env.document.getElementById('app').querySelector('.resume-card button'), 'unchanged challenge payload resumes after reload');
revisionLevel.stages[0].items.push({ ...stage.items[0], text: 'New classification added by content update' });
SD.ui.showHome();
check(!env.document.getElementById('app').querySelector('.resume-card button'), 'same-title changed question data invalidates old checkpoint');
revisionLevel.stages[0].items.pop();
revisionLevel.stages[1].verify = function () { return true; };
SD.session = { level: revisionLevel, stageIdx: 1, firstTry: 0, total: 0, pendingXP: 0, replay: false };
SD.ui.runStage(); env.flush(); SD.ui.showHome(); SD.state = SD.loadState();
revisionLevel.stages[1].verify = function () { return false; };
SD.ui.showHome();
check(!env.document.getElementById('app').querySelector('.resume-card button'), 'same-title changed function predicate invalidates old checkpoint');
console.log(`${checks} progress, restart and XP-farming regression checks pass`);
